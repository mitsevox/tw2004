#!/usr/bin/env python3
"""Generate the C of the data-only Nintendo SDK units from the user's own main.dol.

Two units of the AX audio library hold nothing but data: AXComp.c (__AXCompressorTable) and
DSPCode.c (axDspSlave, the DSP microcode, and axDspSlaveLength). No public decomp has them, and
their bytes are Nintendo's, so the repository never holds them: configure.py runs this script (and
build.ninja reruns it when its inputs change) to write build/<version>/gen/<unit>.c from
orig/<version>/sys/main.dol, which every build already needs. build/ is git-ignored.

Each symbol's section, address, size and alignment come from config/<version>/symbols.txt; the
element type is the SDK header's (dolphin/ax.h, dolphin/ax/__ax.h).

    python tools/build/gendata.py --dol orig/GW4E69/sys/main.dol \
        --symbols config/GW4E69/symbols.txt -o build/GW4E69/gen
"""

import argparse
import re
import struct
import sys
from pathlib import Path

# unit file -> its symbols in definition order: (name, C element type, element size, scalar)
UNITS = {
    "AXComp.c": [
        ("__AXCompressorTable", "unsigned short", 2, False),
    ],
    "DSPCode.c": [
        ("axDspSlave", "unsigned short", 2, False),
        ("axDspSlaveLength", "unsigned short", 2, True),  # .sdata: 2 bytes, padded to 8
    ],
}

SYMBOL_RE = re.compile(
    r"^(\S+)\s*=\s*(\.\w+):0x([0-9A-Fa-f]+);\s*//.*?size:0x([0-9A-Fa-f]+)(.*)$"
)


def read_symbols(path):
    symbols = {}
    for line in Path(path).read_text().splitlines():
        m = SYMBOL_RE.match(line)
        if not m:
            continue
        name, section, addr, size, rest = m.groups()
        align = re.search(r"\balign:(\d+)", rest)
        symbols[name] = (section, int(addr, 16), int(size, 16), int(align.group(1)) if align else None)
    return symbols


def dol_reader(path):
    """Return read(addr, size) over the DOL's text and data sections (header: 7 text + 11 data)."""
    dol = Path(path).read_bytes()
    offsets = struct.unpack_from(">18I", dol, 0x00)
    addrs = struct.unpack_from(">18I", dol, 0x48)
    sizes = struct.unpack_from(">18I", dol, 0x90)
    sections = [(a, s, o) for o, a, s in zip(offsets, addrs, sizes) if s]

    def read(addr, size):
        for base, length, offset in sections:
            if base <= addr and addr + size <= base + length:
                start = offset + addr - base
                return dol[start:start + size]
        sys.exit(f"gendata: 0x{addr:08X}+0x{size:X} is not in an initialised section of {path}")

    return read


def generate(dol, symbols_path, out_dir):
    read = dol_reader(dol)
    symbols = read_symbols(symbols_path)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    fmt = {1: "B", 2: "H", 4: "I"}
    for unit, entries in UNITS.items():
        lines = [
            f"// {unit}: GENERATED by tools/build/gendata.py from the user's own main.dol at build",
            "// time. Nintendo SDK data (the AX library): never committed to the repository.",
            "",
        ]
        for name, ctype, width, scalar in entries:
            if name not in symbols:
                sys.exit(f"gendata: {name} is not in {symbols_path}")
            section, addr, size, align = symbols[name]
            if section not in (".data", ".sdata"):
                sys.exit(f"gendata: {name} is in {section}; only initialised data is handled")
            attr = f" __attribute__((aligned({align})))" if align else ""
            if scalar:
                (value,) = struct.unpack(">" + fmt[width], read(addr, width))
                lines.append(f"{ctype} {name}{attr} = 0x{value:0{width * 2}X};")
            else:
                count = size // width
                values = struct.unpack(f">{count}{fmt[width]}", read(addr, count * width))
                lines.append(f"{ctype} {name}[{count}]{attr} = {{")
                per_row = 16 // width * 2
                for i in range(0, count, per_row):
                    row = ", ".join(f"0x{v:0{width * 2}X}" for v in values[i:i + per_row])
                    lines.append(f"    {row},")
                lines.append("};")
            lines.append("")
        text = "\n".join(lines)
        path = out_dir / unit
        if not path.exists() or path.read_text() != text:
            path.write_text(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dol", required=True, help="the original main.dol")
    parser.add_argument("--symbols", required=True, help="config/<version>/symbols.txt")
    parser.add_argument("-o", "--out-dir", required=True, help="where to write the units' C")
    args = parser.parse_args()
    generate(args.dol, args.symbols, args.out_dir)


if __name__ == "__main__":
    main()
